"""
Main implementation module for SCRUM-14.
This module contains the main function to display the message "wow! we have done it :)".
"""

def display_message():
    """
    Function to display the message "wow! we have done it :)".

    Returns:
        str: The message to be displayed.
    """
    message = "wow! we have done it :)"
    print(message)
    return message


if __name__ == "__main__":
    # Entry point of the program
    display_message()
